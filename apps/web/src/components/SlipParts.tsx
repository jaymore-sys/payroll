import type { ReactNode } from 'react';

/** Shared building blocks for printable payslips (RazorpayX payslip layout). */
export const amt = (n: number) => Math.round(n).toLocaleString('en-IN');
export const dmy = (d?: string | null) => (d ? `${d.slice(8, 10)}/${d.slice(5, 7)}/${d.slice(0, 4)}` : null);
const MON = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
export const shortMonth = (m: string) => `${MON[Number(m.slice(5, 7)) - 1]} ${m.slice(0, 4)}`;

const tone = {
  green: { line: '#16a34a', dot: '#4ade80', bg: 'rgba(34,197,94,0.07)', total: 'rgba(34,197,94,0.12)' },
  orange: { line: '#f97316', dot: '#e11d48', bg: 'rgba(244,63,94,0.05)', total: 'rgba(244,63,94,0.08)' },
  blue: { line: '#6366f1', dot: '#818cf8', bg: 'rgba(99,102,241,0.05)', total: 'rgba(99,102,241,0.09)' },
};
export type Tone = keyof typeof tone;

export function PrintStyles() {
  return (
    <style>{`
      @page { size: A4; margin: 0 }
      html, body { background: #e5e7eb !important; color-scheme: light }
      .slip-page { width: 210mm; min-height: 297mm; margin: 16px auto; background: #fff; box-shadow: 0 4px 24px rgba(0,0,0,.12); display: flex; flex-direction: column; position: relative; overflow: hidden; }
      @media print { html, body { background: #fff !important } .slip-page { margin: 0; box-shadow: none; min-height: 296mm; height: 296mm; } .slip-page + .slip-page { break-before: page; } .no-print { display: none !important } }
      @media screen and (max-width: 820px) { .slip-page { width: 100%; min-height: auto; margin: 0 0 12px; } }
    `}</style>
  );
}

export function Page({ children, n, of }: { children: ReactNode; n: number; of: number }) {
  return (
    <div className="slip-page text-[12px] text-slate-800">
      <div className="flex-1 px-[9mm] pt-[8mm]">{children}</div>
      <div className="flex justify-between px-[9mm] pb-[6mm] pt-4 text-[9.5px] text-slate-500"><span>Page {n} of {of}</span><span>This is a computer generated payslip and does not require a signature</span></div>
    </div>
  );
}

export function SlipHeader({ company, month, logo = '/company-logo.png' }: { company: string; month: string; logo?: string }) {
  return (
    <>
      {/* soft decorative shapes like the RazorpayX payslip */}
      <div className="pointer-events-none absolute left-[9mm] top-[34mm] h-24 w-20 -skew-x-[30deg] bg-gradient-to-br from-orange-100/70 to-sky-100/50" />
      <div className="pointer-events-none absolute right-[9mm] top-[40mm] h-14 w-32 -skew-x-[40deg] bg-gradient-to-r from-amber-50 to-rose-50" />
      <div className="relative flex items-center gap-6 border-b border-slate-100 pb-4">
        <img src={logo} alt="" className="h-12 w-auto object-contain" onError={(e) => ((e.target as HTMLImageElement).style.display = 'none')} />
        <p className="flex-1 text-[13px] font-bold uppercase">{company}</p>
        <div className="border-l border-slate-200 pl-4">
          <p className="text-[13px] font-bold">Payslip: {shortMonth(month)}</p>
          <p className="text-[8.5px] text-slate-500">Generated by <b className="text-violet-700">Valencia Payroll</b></p>
        </div>
      </div>
    </>
  );
}

export function Summary({ net, gross, deductions, grossLabel = 'Gross Pay (A)', dedLabel = 'Deductions (B)' }: { net: number; gross: number; deductions: number; grossLabel?: string; dedLabel?: string }) {
  return (
    <div className="relative ml-[46mm] mt-5 flex items-center gap-5">
      <div><p className="text-[11px] font-semibold text-slate-500">Net Pay</p><p className="text-[16px] font-extrabold">{amt(net)}</p></div>
      <span className="text-xl text-slate-400">=</span>
      <div className="border-l-[3px] border-green-500 pl-2"><p className="text-[11px] text-slate-500">{grossLabel}</p><p className="font-bold">+ {amt(gross)}</p></div>
      {deductions > 0 && <div className="ml-6 border-l-[3px] border-rose-400 pl-2"><p className="text-[11px] text-slate-500">{dedLabel}</p><p className="font-bold">- {amt(deductions)}</p></div>}
    </div>
  );
}

export function InfoColumn({ rows }: { rows: [string, ReactNode][] }) {
  return (
    <dl className="space-y-[14px]">
      {rows.filter(([, v]) => v !== null && v !== undefined && v !== '').map(([k, v]) => (
        <div key={k}><dt className="text-[10.5px] text-slate-500">{k}</dt><dd className="text-[11px] font-bold">{v}</dd></div>
      ))}
    </dl>
  );
}

/** A titled table with the coloured timeline on the left (Gross Pay, Deductions, Yearly Taxable Income …). */
export function Section({ title, sub, t, head, rows, total, note }: {
  title: string; sub?: string; t: Tone; head: string[]; rows: (string | number)[][]; total?: [string, number | string]; note?: ReactNode;
}) {
  const c = tone[t];
  const num = (v: string | number) => (typeof v === 'number' ? amt(v) : v);
  return (
    <div className="relative mb-5 pl-5">
      <span className="absolute bottom-3 left-0 top-3 w-[1.5px] rounded" style={{ background: c.line }} />
      <span className="absolute left-0 top-3 h-[1.5px] w-5" style={{ background: c.line }} />
      <span className="absolute -left-[3px] bottom-1 h-2 w-2 rotate-45" style={{ background: c.dot }} />
      <p className="mb-2 flex items-center gap-2 pl-2 text-[11.5px] font-bold">{title}<span className="h-1.5 w-1.5 rotate-45" style={{ background: c.dot }} />{sub && <span className="text-[9.5px] font-normal text-slate-500">{sub}</span>}</p>
      <table className="w-full text-left">
        <thead><tr style={{ background: c.bg }}>{head.map((h, i) => <th key={h} className={`px-3 py-2.5 text-[10.5px] font-bold ${i ? 'text-right' : ''}`}>{h}</th>)}</tr></thead>
        <tbody>{rows.map((r, k) => (
          <tr key={k} style={{ background: k % 2 ? c.bg : 'transparent' }}>{r.map((v, i) => <td key={i} className={`px-3 py-2.5 ${i ? 'text-right tabular-nums' : 'text-slate-500'}`}>{num(v)}</td>)}</tr>
        ))}</tbody>
      </table>
      {total && <div className="flex justify-end gap-10 px-3 py-2.5 font-bold" style={{ background: c.total }}><span>{total[0]}</span><span className="min-w-[60px] text-right tabular-nums">{num(total[1])}</span></div>}
      {note && <p className="mt-2 pl-2 text-[9.5px] text-slate-500">{note}</p>}
    </div>
  );
}
